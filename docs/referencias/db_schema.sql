CREATE TABLE IF NOT EXISTS `usuario_vacunas` (
	`id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`usuario_id` INTEGER NOT NULL,
	`vacuna_id` INTEGER NOT NULL,
	`nro_dosis` INTEGER,
	`fecha_aplicacion` DATE NOT NULL,
	`lote` VARCHAR(255) NOT NULL,
